begin
	### Step 1: Required packages
	using Catlab.WiringDiagrams
	using Catlab.Graphs
	using Catlab.GraphvizGraphs
	using Compose
	
	
	# Step 2: Define the wiring diagram
	outer_inputs = [:outer_input]
	outer_outputs = [:outer_output]
	
	wd = WiringDiagram(outer_inputs, outer_outputs)
	
	# Define the input and output ports for each box
	spec_ports_in = [:spec_input]
	spec_ports_out = [:spec_output]
	
	template_ports_in = [:template_input]
	template_ports_out = [:template_output]
	
	codefrag_ports_in = [:codefrag_input]
	codefrag_ports_out = [:codefrag_output]
	
	codeout_ports_in = [:codeout_input]
	codeout_ports_out = []
	
	# Add boxes with proper input and output ports
	spec_box = add_box!(wd, Box(:Specification, spec_ports_in, spec_ports_out))
	template_box = add_box!(wd, Box(:Template, template_ports_in, template_ports_out))
	codefrag_box = add_box!(wd, Box(:CodeFragment, codefrag_ports_in, codefrag_ports_out))
	codeout_box = add_box!(wd, Box(:CodeOutput, codeout_ports_in, codeout_ports_out))
	
	# Connect wires between boxes
	add_wire!(wd, (spec_box, 1) => (template_box, 1))
	add_wire!(wd, (template_box, 1) => (codefrag_box, 1))
	add_wire!(wd, (codefrag_box, 1) => (codeout_box, 1))
	
	# Step 3: Convert wiring diagram to Graphviz format
	output = to_graphviz(wd)


end

